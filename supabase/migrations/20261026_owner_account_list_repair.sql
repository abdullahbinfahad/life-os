-- Repair the owner account directory RPC if it is missing or stale.
-- Additive and rerunnable; does not change owner identity or read account records
-- during migration execution.

-- Keep audit storage setup safe on projects where the owner-admin migration has
-- already created these objects.
create table if not exists public.lifeos_admin_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid not null,
  target_user_id uuid,
  action text not null check (
    action in (
      'user-list',
      'user-view',
      'snapshot-update',
      'media-url-request',
      'navigation-update',
      'audit-read'
    )
  ),
  metadata jsonb not null default '{}'::jsonb
    check (pg_catalog.jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default pg_catalog.now()
);

create index if not exists lifeos_admin_audit_created_at_idx
  on public.lifeos_admin_audit (created_at desc, id desc);
create index if not exists lifeos_admin_audit_target_created_at_idx
  on public.lifeos_admin_audit (target_user_id, created_at desc, id desc);

alter table public.lifeos_admin_audit enable row level security;
alter table public.lifeos_admin_audit force row level security;
revoke all on table public.lifeos_admin_audit from public, anon, authenticated;

create or replace function public.lifeos_admin_list_users(
  p_limit integer default 25,
  p_offset integer default 0
)
returns table (
  user_id uuid,
  email text,
  phone text,
  display_name text,
  created_at timestamptz,
  last_sign_in_at timestamptz,
  email_confirmed boolean,
  snapshot_updated_at timestamptz,
  has_snapshot boolean
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.lifeos_is_owner_admin() then
    raise insufficient_privilege using message = 'Owner authorization required';
  end if;

  if p_limit is null or p_limit < 1 or p_limit > 100 then
    raise exception using
      errcode = '22023',
      message = 'p_limit must be between 1 and 100';
  end if;
  if p_offset is null or p_offset < 0 or p_offset > 10000 then
    raise exception using
      errcode = '22023',
      message = 'p_offset must be between 0 and 10000';
  end if;

  insert into public.lifeos_admin_audit (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    null,
    'user-list',
    pg_catalog.jsonb_build_object('limit', p_limit, 'offset', p_offset)
  );

  return query
  select
    u.id,
    u.email,
    u.phone,
    pg_catalog.left(
      pg_catalog.coalesce(
        pg_catalog.nullif(u.raw_user_meta_data ->> 'full_name', ''),
        pg_catalog.nullif(u.raw_user_meta_data ->> 'name', ''),
        pg_catalog.nullif(u.raw_user_meta_data ->> 'display_name', ''),
        u.email,
        u.phone,
        'Unnamed account'
      ),
      120
    ) as display_name,
    u.created_at,
    u.last_sign_in_at,
    (u.email_confirmed_at is not null) as email_confirmed,
    d.updated_at,
    (d.user_id is not null) as has_snapshot
  from auth.users as u
  left join public.life_data as d on d.user_id = u.id
  order by u.created_at desc nulls last, u.id asc
  limit p_limit
  offset p_offset;
end;
$$;

revoke all on function public.lifeos_admin_list_users(integer, integer) from public, anon;
grant execute on function public.lifeos_admin_list_users(integer, integer) to authenticated;

-- Read-only catalog verification; this returns the resolved function signature.
select pg_catalog.to_regprocedure('public.lifeos_admin_list_users(integer,integer)')
  as installed_function;

notify pgrst, 'reload schema';
