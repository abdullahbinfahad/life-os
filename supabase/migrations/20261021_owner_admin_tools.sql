-- Owner-admin tools for private Life OS operations.
-- This migration is additive: it adds narrowly scoped SECURITY DEFINER APIs rather
-- than broadening normal users' self-only access to public.life_data.

-- The audit table deliberately has no foreign keys to auth.users so historical
-- audit evidence is retained if an account is later deleted. Its metadata is
-- constrained to JSON objects and the exposed APIs write only safe summaries.
create table if not exists public.lifeos_admin_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid not null,
  target_user_id uuid,
  action text not null check (
    action in (
      'user-list',
      'user-view',
      'snapshot-update',
      'media-url-request',
      'navigation-update',
      'audit-read'
    )
  ),
  metadata jsonb not null default '{}'::jsonb
    check (pg_catalog.jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default pg_catalog.now()
);

create index if not exists lifeos_admin_audit_created_at_idx
  on public.lifeos_admin_audit (created_at desc, id desc);
create index if not exists lifeos_admin_audit_target_created_at_idx
  on public.lifeos_admin_audit (target_user_id, created_at desc, id desc);

alter table public.lifeos_admin_audit enable row level security;
alter table public.lifeos_admin_audit force row level security;

-- No table grants and no RLS policy are provided to browser roles. The table is
-- reachable only through the guarded SECURITY DEFINER functions below.
revoke all on table public.lifeos_admin_audit from public, anon, authenticated;

comment on table public.lifeos_admin_audit is
  'Private owner-admin audit trail. Metadata must contain only safe operational summaries, never snapshot or media content.';
comment on column public.lifeos_admin_audit.target_user_id is
  'Nullable for global operations (user listing, audit reading, and navigation changes).';

-- List operational account fields only; auth credentials, token fields, and raw
-- metadata blobs are intentionally never selected into this API's result.
create or replace function public.lifeos_admin_list_users(
  p_limit integer default 25,
  p_offset integer default 0
)
returns table (
  user_id uuid,
  email text,
  phone text,
  display_name text,
  created_at timestamptz,
  last_sign_in_at timestamptz,
  email_confirmed boolean,
  snapshot_updated_at timestamptz,
  has_snapshot boolean
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.lifeos_is_owner_admin() then
    raise insufficient_privilege using message = 'Owner authorization required';
  end if;

  -- Bound pagination to prevent expensive, unbounded scans through auth.users.
  if p_limit is null or p_limit < 1 or p_limit > 100 then
    raise exception using
      errcode = '22023',
      message = 'p_limit must be between 1 and 100';
  end if;
  if p_offset is null or p_offset < 0 or p_offset > 10000 then
    raise exception using
      errcode = '22023',
      message = 'p_offset must be between 0 and 10000';
  end if;

  insert into public.lifeos_admin_audit (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    null,
    'user-list',
    pg_catalog.jsonb_build_object('limit', p_limit, 'offset', p_offset)
  );

  return query
  select
    u.id,
    u.email,
    u.phone,
    pg_catalog.left(
      pg_catalog.coalesce(
        pg_catalog.nullif(u.raw_user_meta_data ->> 'full_name', ''),
        pg_catalog.nullif(u.raw_user_meta_data ->> 'name', ''),
        pg_catalog.nullif(u.raw_user_meta_data ->> 'display_name', ''),
        u.email,
        u.phone,
        'Unnamed account'
      ),
      120
    ) as display_name,
    u.created_at,
    u.last_sign_in_at,
    (u.email_confirmed_at is not null) as email_confirmed,
    d.updated_at,
    (d.user_id is not null) as has_snapshot
  from auth.users as u
  left join public.life_data as d on d.user_id = u.id
  order by u.created_at desc nulls last, u.id asc
  limit p_limit
  offset p_offset;
end;
$$;

revoke all on function public.lifeos_admin_list_users(integer, integer) from public, anon;
grant execute on function public.lifeos_admin_list_users(integer, integer) to authenticated;

-- Return one selected account record plus its private Life OS snapshot. The
-- selected display name is an extracted scalar only; no raw metadata JSON is
-- returned.
create or replace function public.lifeos_admin_get_user(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
  v_has_snapshot boolean;
begin
  if not public.lifeos_is_owner_admin() then
    raise insufficient_privilege using message = 'Owner authorization required';
  end if;
  if p_user_id is null then
    raise exception using errcode = '22023', message = 'p_user_id is required';
  end if;

  select
    pg_catalog.jsonb_build_object(
      'account', pg_catalog.jsonb_build_object(
        'id', u.id,
        'email', u.email,
        'phone', u.phone,
        'display_name', pg_catalog.left(
          pg_catalog.coalesce(
            pg_catalog.nullif(u.raw_user_meta_data ->> 'full_name', ''),
            pg_catalog.nullif(u.raw_user_meta_data ->> 'name', ''),
            pg_catalog.nullif(u.raw_user_meta_data ->> 'display_name', ''),
            u.email,
            u.phone,
            'Unnamed account'
          ),
          120
        ),
        'created_at', u.created_at,
        'last_sign_in_at', u.last_sign_in_at,
        'email_confirmed', (u.email_confirmed_at is not null)
      ),
      'life_data',
        case when d.user_id is null then null
        else pg_catalog.jsonb_build_object(
          'data', d.data,
          'updated_at', d.updated_at
        )
        end
    ),
    (d.user_id is not null)
  into v_result, v_has_snapshot
  from auth.users as u
  left join public.life_data as d on d.user_id = u.id
  where u.id = p_user_id;

  if not found then
    raise no_data_found using message = 'Account not found';
  end if;

  insert into public.lifeos_admin_audit (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    p_user_id,
    'user-view',
    pg_catalog.jsonb_build_object('has_snapshot', v_has_snapshot)
  );

  return v_result;
end;
$$;

revoke all on function public.lifeos_admin_get_user(uuid) from public, anon;
grant execute on function public.lifeos_admin_get_user(uuid) to authenticated;

-- Update only an existing snapshot and require the caller's last observed
-- updated_at value. This prevents an admin from silently overwriting a newer
-- concurrent save; it never upserts a missing row.
create or replace function public.lifeos_admin_update_user_snapshot(
  p_user_id uuid,
  p_data jsonb,
  p_expected_updated_at timestamptz
)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_updated_at timestamptz;
  v_data_bytes integer;
begin
  if not public.lifeos_is_owner_admin() then
    raise insufficient_privilege using message = 'Owner authorization required';
  end if;
  if p_user_id is null then
    raise exception using errcode = '22023', message = 'p_user_id is required';
  end if;
  if p_expected_updated_at is null then
    raise exception using errcode = '22023', message = 'p_expected_updated_at is required';
  end if;
  if p_data is null or pg_catalog.jsonb_typeof(p_data) <> 'object' then
    raise exception using errcode = '22023', message = 'p_data must be a JSON object';
  end if;

  v_data_bytes := pg_catalog.octet_length(p_data::text);
  if v_data_bytes > 1048576 then
    raise exception using
      errcode = '22023',
      message = 'p_data exceeds the 1 MiB serialized snapshot limit';
  end if;

  update public.life_data
  set
    data = p_data,
    updated_at = pg_catalog.clock_timestamp()
  where user_id = p_user_id
    and updated_at = p_expected_updated_at
  returning updated_at into v_updated_at;

  if not found then
    perform 1
    from public.life_data as d
    where d.user_id = p_user_id;

    if found then
      raise exception using
        errcode = '40001',
        message = 'Snapshot has changed; reload before saving';
    end if;

    raise no_data_found using message = 'Snapshot not found; admin updates never create snapshots';
  end if;

  -- The audit record contains exactly a deterministic content hash and byte
  -- count; the private JSON snapshot itself is never copied into the audit log.
  insert into public.lifeos_admin_audit (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    p_user_id,
    'snapshot-update',
    pg_catalog.jsonb_build_object(
      'data_md5', pg_catalog.md5(p_data::text),
      'data_bytes', v_data_bytes
    )
  );

  return v_updated_at;
end;
$$;

revoke all on function public.lifeos_admin_update_user_snapshot(uuid, jsonb, timestamptz) from public, anon;
grant execute on function public.lifeos_admin_update_user_snapshot(uuid, jsonb, timestamptz) to authenticated;

-- The audit-read event is written directly, rather than by calling this
-- function recursively, so every audit read is recorded exactly once.
create or replace function public.lifeos_admin_list_audit(p_limit integer default 50)
returns table (
  id bigint,
  actor_id uuid,
  target_user_id uuid,
  action text,
  metadata jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.lifeos_is_owner_admin() then
    raise insufficient_privilege using message = 'Owner authorization required';
  end if;
  if p_limit is null or p_limit < 1 or p_limit > 100 then
    raise exception using
      errcode = '22023',
      message = 'p_limit must be between 1 and 100';
  end if;

  insert into public.lifeos_admin_audit (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    null,
    'audit-read',
    pg_catalog.jsonb_build_object('limit', p_limit)
  );

  return query
  select
    a.id,
    a.actor_id,
    a.target_user_id,
    a.action,
    a.metadata,
    a.created_at
  from public.lifeos_admin_audit as a
  order by a.created_at desc, a.id desc
  limit p_limit;
end;
$$;

